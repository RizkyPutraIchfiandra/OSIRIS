import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,

  /* One legacy component exhausts the heap inside the React Compiler rules.
   *
   * `WorldRemote.tsx` is 65 KB of upstream dashboard code and, on its own, makes
   * `react-hooks/*` allocate past the Node limit — no single rule is to blame,
   * because the plugin analyses the whole program. The other large components
   * lint in seconds, so this is scoped to the one file rather than switching the
   * compiler rules off everywhere (NusaWatch and new code keep them).
   *
   * The rule list is derived from the preset so it cannot drift when
   * eslint-config-next adds a compiler rule. Remove this block if the component
   * is split up or the upstream plugin stops blowing up. */
  {
    files: ["src/components/WorldRemote.tsx"],
    rules: Object.fromEntries(
      [...nextVitals, ...nextTs]
        .flatMap(config => Object.keys(config.rules ?? {}))
        .filter(rule => rule.startsWith("react-hooks/"))
        .map(rule => [rule, "off"]),
    ),
  },

  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Machine-generated, 1.3 MB on a single line. Linting it exhausts the
    // Node heap before it can report anything, which made `npm run lint`
    // unusable for the rest of the repository. Regenerated by
    // tools/generate-transit-routes.mjs, so there is nothing to review here.
    "src/lib/transit-routes.generated.ts",
  ]),
]);

export default eslintConfig;
